/**
 * Retrieve coordinates for district.
 * If district is not indexed, check state center.
 * Never silently fallback to Meerut.
 */
export function getDistrictCoordinates(districtName, stateName) {
  if (districtName && typeof districtName === "string") {
    const cleanDist = districtName.trim();
    if (DISTRICT_COORDINATES[cleanDist]) {
      return DISTRICT_COORDINATES[cleanDist];
    }
    const foundKey = Object.keys(DISTRICT_COORDINATES).find(
      (k) => k.toLowerCase() === cleanDist.toLowerCase()
    );
    if (foundKey) {
      return DISTRICT_COORDINATES[foundKey];
    }
  }

  // Fallback to State Center if state provided
  if (stateName && typeof stateName === "string") {
    const cleanState = stateName.trim();
    if (STATE_CENTERS[cleanState]) {
      return STATE_CENTERS[cleanState];
    }
    const foundStateKey = Object.keys(STATE_CENTERS).find(
      (s) => s.toLowerCase() === cleanState.toLowerCase() ||
             cleanState.toLowerCase().includes(s.toLowerCase())
    );
    if (foundStateKey) {
      return STATE_CENTERS[foundStateKey];
    }
  }

  // Return null so the caller knows coordinates need resolution or user prompt
  return null;
}

/**
 * Async reverse/search geocoding with timeout via Nominatim
 */
export async function geocodeLocationOnline(district, state, timeoutMs = 8000) {
  if (!district && !state) return null;
  const queryStr = [district, state, "India"].filter(Boolean).join(", ");

  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), timeoutMs);

  try {
    const res = await fetch(
      `https://nominatim.openstreetmap.org/search?format=json&q=${encodeURIComponent(queryStr)}&limit=1`,
      {
        headers: {
          "User-Agent": "VyapaarAI-Geocoding/1.0",
          "Accept-Language": "en,hi",
        },
        signal: controller.signal,
      }
    );
    clearTimeout(timer);

    if (!res.ok) return null;
    const data = await res.json();
    if (Array.isArray(data) && data.length > 0 && data[0].lat && data[0].lon) {
      return [parseFloat(data[0].lat), parseFloat(data[0].lon)];
    }
  } catch (err) {
    console.warn("Online geocoding attempt failed or timed out:", err?.message || err);
  } finally {
    clearTimeout(timer);
  }
  return null;
}

// Convert business category to Overpass OSM tag
export function getCategoryOsmTag(categoryName) {
  const cat = (categoryName || "").toLowerCase();
  if (cat.includes("dairy") || cat.includes("milk") || cat.includes("डेयरी")) {
    return '["shop"="dairy"]';
  }
  if (
    cat.includes("kirana") ||
    cat.includes("grocery") ||
    cat.includes("general") ||
    cat.includes("convenience") ||
    cat.includes("किराना")
  ) {
    return '["shop"="convenience"]';
  }
  if (
    cat.includes("tailor") ||
    cat.includes("garment") ||
    cat.includes("weaving") ||
    cat.includes("सिलाई")
  ) {
    return '["craft"="tailor"]';
  }
  if (
    cat.includes("vegetable") ||
    cat.includes("fruit") ||
    cat.includes("फल") ||
    cat.includes("सब्जी")
  ) {
    return '["shop"="greengrocer"]';
  }
  if (
    cat.includes("poultry") ||
    cat.includes("egg") ||
    cat.includes("chicken") ||
    cat.includes("पोल्ट्री")
  ) {
    return '["shop"="butcher"]';
  }
  if (cat.includes("hardware") || cat.includes("हार्डवेयर")) {
    return '["shop"="hardware"]';
  }
  if (
    cat.includes("tea") ||
    cat.includes("dhaba") ||
    cat.includes("eatery") ||
    cat.includes("food cart") ||
    cat.includes("चाय")
  ) {
    return '["amenity"="cafe"]';
  }
  if (
    cat.includes("mobile") ||
    cat.includes("repair") ||
    cat.includes("photocopy") ||
    cat.includes("मोबाइल")
  ) {
    return '["shop"="mobile_phone"]';
  }
  if (cat.includes("salon") || cat.includes("beauty") || cat.includes("ब्यूटी")) {
    return '["shop"="hairdresser"]';
  }
  if (
    cat.includes("bakery") ||
    cat.includes("food processing") ||
    cat.includes("बेकरी")
  ) {
    return '["shop"="bakery"]';
  }
  if (
    cat.includes("carpenter") ||
    cat.includes("blacksmith") ||
    cat.includes("artisan") ||
    cat.includes("बढ़ई")
  ) {
    return '["craft"="carpenter"]';
  }
  return '["shop"="convenience"]';
}
